-- 010：重新修复邀请码备注乱码（第一版 009 的反解方案原理上不可行）
--
-- 背景（2026-11-10 用户反馈，第三次修复）：
--   上一轮部署后备注仍是乱码。复盘发现 009 的反解 SQL 从原理上就不成立：
--   原文「部署脚本生成」的 UTF-8 末字节是 0x90，而 MySQL 的 latin1 实为
--   cp1252，0x90 在 cp1252 中是**未定义字符**——在首次写入阶段该字节
--   就已被替换成 '?'，原始信息永久丢失，CONVERT(... USING latin1)
--   无法还原。故 009 虽已登记执行，实际并未修复任何数据。
--
-- 修复策略（不猜原文、不做反解）：
--   库中所有由部署脚本生成的备注，原文都是固定字符串「部署脚本生成」。
--   凡是「非空、且不含任何中文」的备注，一律判定为乱码残留，
--   直接改写为「部署脚本生成」。
--   · 正常中文备注（含中文）不满足条件，不会被误改；
--   · 管理员手填的中文备注同样含中文，不会被误改；
--   · 纯英文备注会被改写，但邀请码备注在本系统无英文场景，可接受。
--
-- 幂等：修完后备注含中文，条件不再命中，重复执行无副作用。
--
-- 用 CONVERT(... USING utf8mb4) 包裹字面量，确保写入字节正确，
-- 不受会话字符集影响。
--
-- 依赖：001 ~ 009。由 schema_migrations 保证只执行一次。
-- ============================================================================

UPDATE invite_codes
   SET note = CONVERT('部署脚本生成' USING utf8mb4)
 WHERE note IS NOT NULL
   AND note <> ''
   AND note NOT REGEXP '[一-龥]';
