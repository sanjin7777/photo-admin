--
-- 背景（2026-11-10 用户反馈，第二次修复）：
--   后台「邀请码」列表「备注」列显示为 é¨ç½²è„šæœ¬ç”Ÿæˆ 一类乱码。
--
-- 根因：
--   deploy/gen-invite-codes.sh 早期版本调用 `mysql` 客户端时没有指定
--   --default-character-set=utf8mb4。容器内 locale 为 C/POSIX，
--   客户端把脚本里的 UTF-8 中文按 latin1 解读，服务端再按 utf8mb4 转存，
--   形成双重编码。init-seed.sh 早已踩过同一个坑并显式指定字符集，
--   gen-invite-codes.sh 当时漏了。
--
-- ⚠️ 为什么不能用「反解」修复（第一版方案失败的原因）：
--   原文「部署脚本生成」的 UTF-8 末字节是 0x90，而 MySQL 的 latin1
--   实为 cp1252，0x90 在 cp1252 中是**未定义字符**——在写入阶段该字节
--   就已经被替换成 '?'，原始信息**永久丢失**。
--   因此 CONVERT(... USING latin1) 无法还原原文，任何反解 SQL 都不可行。
--
-- 修复策略（不猜原文、不做反解）：
--   库中所有由部署脚本生成的备注，其原文都是固定字符串「部署脚本生成」。
--   因此：凡是「非空、且不含任何中文」的备注，一律判定为乱码残留，
--   直接改写为「部署脚本生成」。
--   · 正常中文备注（含中文）不满足条件，不会被误改；
--   · 管理员在后台手填的中文备注同样含中文，不会被误改；
--   · 纯英文备注会被改写，但邀请码备注在本系统里没有英文场景，可接受。
--
-- 幂等：修完之后备注含中文，条件不再命中，重复执行无副作用。
--
-- 依赖：001 ~ 008。由 schema_migrations 保证只执行一次。
-- ============================================================================

UPDATE invite_codes
   SET note = '部署脚本生成'
 WHERE note IS NOT NULL
   AND note <> ''
   AND note NOT REGEXP '[一-龥]';
